#!/usr/bin/env node
// Scans app/ and components/ for Iconify icon names ("prefix:name") and
// generates a local, offline subset of the icon sets actually used, so
// <Iconify> never has to fetch icon data from api.iconify.design at runtime.
import { createRequire } from "node:module";
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, extname } from "node:path";

const require = createRequire(import.meta.url);
const { getIconData } = require("@iconify/utils");

const ROOT = join(import.meta.dirname, "..");
const SCAN_DIRS = ["app", "components"];
const OUT_FILE = join(ROOT, "components/iconify/register-icons.generated.ts");

const ICON_LITERAL = /["'`]((?:eva|mdi|mingcute|solar|svg-spinners):[a-z0-9-]+)["'`]/g;

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      if (entry === "node_modules" || entry.startsWith(".")) continue;
      walk(full, files);
    } else if ([".ts", ".tsx"].includes(extname(entry))) {
      files.push(full);
    }
  }
  return files;
}

const iconsByPrefix = new Map();

for (const dir of SCAN_DIRS) {
  for (const file of walk(join(ROOT, dir))) {
    const content = readFileSync(file, "utf8");
    for (const match of content.matchAll(ICON_LITERAL)) {
      const [, fullName] = match;
      const [prefix, name] = fullName.split(":");
      if (!iconsByPrefix.has(prefix)) iconsByPrefix.set(prefix, new Set());
      iconsByPrefix.get(prefix).add(name);
    }
  }
}

const collections = [];

for (const [prefix, names] of iconsByPrefix) {
  const fullSet = require(`@iconify-json/${prefix}/icons.json`);
  const icons = {};
  const missing = [];

  for (const name of names) {
    // Resolved via getIconData (not getIcons) so aliases keep the name the
    // code actually references, instead of being renamed to their parent.
    const data = getIconData(fullSet, name);
    if (!data) {
      missing.push(name);
      continue;
    }
    icons[name] = data;
  }

  if (missing.length) {
    throw new Error(`Icon(s) not found in "${prefix}" set: ${missing.join(", ")}`);
  }

  collections.push({
    prefix,
    icons,
    width: fullSet.width,
    height: fullSet.height,
  });
}

collections.sort((a, b) => a.prefix.localeCompare(b.prefix));

const banner = `// AUTO-GENERATED by scripts/generate-icon-subset.mjs — do not edit by hand.
// Regenerate with \`npm run icons:build\` after adding/removing <Iconify icon="..."/> usages.
import type { IconifyJSON } from "@iconify/types";

export const iconSets: IconifyJSON[] = ${JSON.stringify(collections, null, 2)};
`;

writeFileSync(OUT_FILE, banner);

const total = collections.reduce((sum, c) => sum + Object.keys(c.icons).length, 0);
console.log(
  `[icons:build] wrote ${collections.length} icon set(s), ${total} icon(s) -> ${OUT_FILE.replace(ROOT + "/", "")}`,
);
